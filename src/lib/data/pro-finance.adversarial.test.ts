test('aging uses Dubai business date and only eligible open invoices', () => {
  const dashboard = calculateProFinanceDashboard({
    tenantId: 't1',
    today: '2026-09-02',
    companies: [{ id: 'c1', tenant_id: 't1', company_name: 'Assigned' }],
    payments: [],
    refunds: [],
    invoices: [
      {
        id: 'overdue',
        tenant_id: 't1',
        company_id: 'c1',
        amount_minor: 100,
        currency: 'AED',
        status: 'open',
        due_at: '2026-09-01',
        created_at: '2026-09-01T00:00:00Z',
      },
      {
        id: 'due',
        tenant_id: 't1',
        company_id: 'c1',
        amount_minor: 200,
        currency: 'AED',
        status: 'open',
        due_at: '2026-09-02',
        created_at: '2026-09-01T00:00:00Z',
      },
      {
        id: 'draft',
        tenant_id: 't1',
        company_id: 'c1',
        amount_minor: 999,
        currency: 'AED',
        status: 'draft',
        due_at: '2026-08-01',
        created_at: '2026-09-01T00:00:00Z',
      },
    ],
  });
  assert.deepEqual(
    dashboard.aging.map((row) => [row.key, row.amountMinor]),
    [
      ['overdue', 100],
      ['due_today', 200],
    ],
  );
});
